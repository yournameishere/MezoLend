// Copies ABIs (from Foundry's out/) and deployed addresses into the web app as typed TS modules.
// Run after `forge build` / redeploys:  npm run sync
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = resolve(here, "../../contracts");
const outDir = resolve(here, "../src/config");
mkdirSync(outDir, { recursive: true });

const names = [
  "LendingPool",
  "BorrowManager",
  "CollateralManager",
  "LiquidationManager",
  "MezoLendLens",
  "MarketRegistry",
  "PriceOracle",
  "InterestRateModel",
];

let abis = "// AUTO-GENERATED by scripts/sync-contracts.mjs — do not edit.\n\n";
for (const n of names) {
  const art = JSON.parse(readFileSync(resolve(contracts, `out/${n}.sol/${n}.json`), "utf8"));
  const camel = n[0].toLowerCase() + n.slice(1);
  abis += `export const ${camel}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
}
writeFileSync(resolve(outDir, "abis.ts"), abis);

const dep = JSON.parse(readFileSync(resolve(contracts, "deployments/mezo-testnet.json"), "utf8"));
const deployment = `// AUTO-GENERATED by scripts/sync-contracts.mjs — do not edit.
export const deployment = ${JSON.stringify(dep, null, 2)} as const;
`;
writeFileSync(resolve(outDir, "deployment.ts"), deployment);
console.log("synced", names.length, "ABIs and deployment", dep.registry);
